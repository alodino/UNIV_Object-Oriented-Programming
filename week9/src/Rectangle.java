public class Rectangle {
    private double height;
    private double width;
    private double area;

    Rectangle(double h, double w)
    {
        this.height = h;
        this.width = w;
        this.area = (h * w);
    }

    public double Area()
    {
        return this.area;
    }

    private double Area_()
    {
        return this.area;
    }
}
